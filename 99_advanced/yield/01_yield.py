"""
`return`은 값을 한 번 반환하고 함수가 종료되지만,
`yield`는 값을 하나씩 반환하고 함수가 일시 정지 상태로 유지됩니다.

---------------------------------------------------------------------
def 안에 yield 가 있다       →  그 함수는 '제너레이터 함수'
    ↓  (컴파일 시점에 결정)
제너레이터 함수를 호출한다       →  '제너레이터 객체'가 나온다 (몸통은 실행 안 됨)
    ↓
제너레이터 객체는 이터레이터다    →  for / list() / sum() 이 그대로 받아 준다
---------------------------------------------------------------------
"""


# return - 한 번에 모든 값 반환
def return_func():
    return [1, 2, 3]  # 리스트 전체를 메모리에 올림


# yield - 하나씩 순서대로 반환
def yield_func():
    yield 1  # 여기서 일시 정지
    yield 2  # 다음 호출 시 여기서 재개
    yield 3
