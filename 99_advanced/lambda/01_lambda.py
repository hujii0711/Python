"""
파이썬의 람다(lambda) 함수는 이름 없이 한 줄로 간단하게 만드는 함수예요.
`def`로 함수를 만드는 것과 같은 역할을 하지만, 훨씬 짧고 간단한 문법을 씁니다.

"lambda 매개변수1, 매개변수2, ... : 표현식"
- `lambda` 키워드로 시작
- 콜론(`:`) 앞에는 매개변수
- 콜론(`:`) 뒤에는 반환할 값(표현식) — `return`을 따로 안 써도 자동으로 반환됨
- 딱 한 줄, 표현식 하나만 쓸 수 있음 (if문, for문 등 여러 줄 로직은 불가)
"""


# 일반 함수로 정의
def add(a, b):
    return a + b


print(add(3, 5))

# 람다 함수로 정의
add = lambda a, b: a + b

print(add(3, 5))
