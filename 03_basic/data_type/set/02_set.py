# 빈 집합을 만들 때는 반드시 이 방법을 써야 합니다.
empty_set = set()
print(type(empty_set))  # <class 'set'>

# `set()`은 다른 자료형(리스트, 튜플, 문자열 등)을 집합으로 변환할 때도 사용합니다.
s1 = set([1, 2, 2, 3, 3, 3])  # 리스트 → 집합, 중복 제거됨
print(s1)  # {1, 2, 3}

s2 = set((1, 2, 3))  # 튜플 → 집합
print(s2)  # {1, 2, 3}

s3 = set("hello")  # 문자열 → 집합 (문자 단위로 분해)
print(s3)  # {'h', 'e', 'l', 'o'}
