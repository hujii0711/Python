"""
구형 방식: .format() 메서드
{} 기호를 플레이스홀더로 두고, 뒤에 .format() 메서드로 값을 채워 넣는 방식입니다. 파이썬 3.0부터 도입되었습니다.
"""

# 1. 순서대로 들어가기
text1 = "나는 {0}를 좋아하고, {1}를 싫어한다.".format("사과", "바나나")

# 2. 이름표(키워드) 지정하기
text2 = "이름: {name}, 나이: {age}".format(name="영희", age=30)

print(text1)  # 출력: 나는 사과를 좋아하고, 바나나를 싫어한다.
print(text2)  # 출력: 이름: 영희, 나이: 30
