"""
| 구분    | 리스트 컴프리헨션 `[]` | 제너레이터 표현식 `()`     |
| ----- | ------------------ | --------------------- |
| 반환값   | 리스트 (전체 값 저장)  | 제너레이터 객체           |
| 메모리   | 모든 요소를 한 번에 저장 | 값을 하나씩 생성 (메모리 절약) |
| 평가 시점 | 즉시 평가(eager)   | 지연 평가(lazy)        |
| 재사용   | 여러 번 순회 가능     | 한 번 순회하면 소진됨       |
"""

# 리스트 컴프리헨션 - 즉시 모든 값을 메모리에 저장
list_comp = [x**2 for x in range(5)]
print(list_comp)  # [0, 1, 4, 9, 16]

# 제너레이터 표현식 - 값을 즉시 만들지 않고 필요할 때 하나씩 생성
gen_exp = (x**2 for x in range(5))
print(gen_exp)  # <generator object ...>
print(list(gen_exp))  # [0, 1, 4, 9, 16] (직접 순회해야 값 확인 가능)
