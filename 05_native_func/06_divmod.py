"""
두 숫자를 나눴을 때 몫과 나머지를 튜플 형태로 한번에 반환합니다.
"""

print(divmod(10, 3))  # (3, 1) → 몫 3, 나머지 1
print(divmod(20, 4))  # (5, 0) → 몫 5, 나머지 0

# 원래는 이렇게 따로 구해야 하는 걸 한번에!
몫 = 10 // 3  # 3
나머지 = 10 % 3  # 1

# divmod로는 한줄로
몫, 나머지 = divmod(10, 3)
print(f"몫: {몫}, 나머지: {나머지}")  # 몫: 3, 나머지: 1

# 활용 예: 초를 분과 초로 변환
총초 = 125
분, 초 = divmod(총초, 60)
print(f"{분}분 {초}초")  # 2분 5초
