"""
리스트 등의 모든 요소에 동일한 함수를 적용해서 새로운 결과를 만들어줍니다.
"""

숫자들 = [1, 2, 3, 4, 5]


# 각 숫자를 제곱하기
def 제곱(x):
    return x**2


결과 = map(제곱, 숫자들)
print(list(결과))  # [1, 4, 9, 16, 25]

# lambda(익명함수)와 함께 더 간결하게
결과2 = map(lambda x: x**2, 숫자들)
print(list(결과2))  # [1, 4, 9, 16, 25]

# 활용 예: 문자열로 된 숫자 리스트를 정수로 한번에 변환
문자열숫자 = ["1", "2", "3"]
정수숫자 = list(map(int, 문자열숫자))
print(정수숫자)  # [1, 2, 3]
