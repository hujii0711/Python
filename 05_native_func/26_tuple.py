"""
리스트, 문자열 등을 튜플(수정 불가능한 순서 있는 자료형)로 변환합니다.
"""

print(tuple([1, 2, 3]))  # (1, 2, 3) (리스트 → 튜플)
print(tuple("abc"))  # ('a', 'b', 'c') (문자열 → 튜플)
print(tuple())  # () (빈 튜플)

# 튜플은 한번 만들면 수정 불가 (리스트와의 차이점)
숫자튜플 = tuple([1, 2, 3])
# 숫자튜플[0] = 100  # TypeError! 튜플은 수정 불가능


# 활용 예: 함수에서 여러 값을 반환할 때 (자동으로 튜플이 됨)
def 최소최대(리스트):
    return min(리스트), max(리스트)


결과 = 최소최대([3, 7, 1, 9])
print(결과)  # (1, 9)
print(type(결과))  # <class 'tuple'>
