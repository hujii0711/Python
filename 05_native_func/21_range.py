"""
일정 범위의 숫자들을 순서대로 생성합니다. `for` 반복문에서 정말 자주 함께 쓰이는 함수예요.
`range(5)`는 0, 1, 2, 3, 4까지만 포함하고 5는 포함하지 않습니다. "끝값 - 1까지"라는 점을 꼭 기억하세요.
"""

# range(끝값) → 0부터 끝값-1까지
print(list(range(5)))  # [0, 1, 2, 3, 4]

# range(시작값, 끝값) → 시작값부터 끝값-1까지
print(list(range(2, 7)))  # [2, 3, 4, 5, 6]

# range(시작값, 끝값, 증가값)
print(list(range(0, 10, 2)))  # [0, 2, 4, 6, 8] (2씩 증가)
print(list(range(10, 0, -1)))  # [10, 9, 8, ..., 1] (거꾸로 감소)

# 활용 예: for문에서 반복 횟수 지정
for i in range(3):
    print(f"{i}번째 반복입니다.")
# 0번째 반복입니다.
# 1번째 반복입니다.
# 2번째 반복입니다.
