"""
문자열, 리스트, 튜플, 딕셔너리 등의 **길이(요소 개수)**를 반환합니다. 정말 자주 쓰이는 필수 함수예요.
"""

print(len("hello"))  # 5 (문자 개수)
print(len([1, 2, 3, 4]))  # 4 (리스트 요소 개수)
print(len((1, 2)))  # 2 (튜플 요소 개수)
print(len({"a": 1, "b": 2}))  # 2 (딕셔너리는 key 개수)

# 활용 예: 반복문과 함께 자주 사용
과일 = ["사과", "바나나", "체리"]
for i in range(len(과일)):
    print(과일[i])

# 활용 예: 빈 리스트인지 확인
장바구니 = []
if len(장바구니) == 0:
    print("장바구니가 비어있습니다.")
