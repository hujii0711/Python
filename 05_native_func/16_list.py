"""
다른 자료형(튜플, 문자열, range 등)을 리스트로 변환합니다.
"""

print(list((1, 2, 3)))  # [1, 2, 3] (튜플 → 리스트)
print(list("hello"))  # ['h', 'e', 'l', 'l', 'o'] (문자열 → 문자 리스트)
print(list(range(5)))  # [0, 1, 2, 3, 4] (range → 리스트)

# 빈 리스트 만들기
빈리스트 = list()
print(빈리스트)  # []
# print([]) 와 동일

# 활용 예: filter, map의 결과를 눈으로 확인할 때
숫자들 = filter(lambda x: x > 5, [1, 5, 8, 10])
print(list(숫자들))  # [8, 10]

# 활용 예: 딕셔너리의 key만 리스트로
정보 = {"이름": "철수", "나이": 20}
print(list(정보))  # ['이름', '나이']
