"""
리스트, 튜플 등을 정렬해서 새로운 리스트로 반환합니다. 원본은 그대로 유지됩니다.
"""

숫자들 = [5, 2, 8, 1, 9]
print(sorted(숫자들))  # [1, 2, 5, 8, 9] (오름차순)
print(sorted(숫자들, reverse=True))  # [9, 8, 5, 2, 1] (내림차순)
print(숫자들)  # [5, 2, 8, 1, 9] (원본은 그대로!)

# 문자열도 정렬 가능
이름들 = ["철수", "영희", "가영"]
print(sorted(이름들))  # ['가영', '영희', '철수'] (가나다순)

# key 옵션으로 정렬 기준 지정 (max/min과 동일한 방식)
단어들 = ["banana", "kiwi", "watermelon"]
print(sorted(단어들, key=len))  # ['kiwi', 'banana', 'watermelon'] (길이순)

# 활용 예: 딕셔너리 리스트를 특정 값 기준으로 정렬
학생들 = [{"이름": "철수", "점수": 85}, {"이름": "영희", "점수": 92}]
결과 = sorted(학생들, key=lambda x: x["점수"], reverse=True)
print(결과)  # 점수 높은 순으로 정렬됨
