"""
여러 개의 리스트(또는 튜플 등)를 같은 순서끼리 짝지어서 묶어줍니다.
"""

이름들 = ["철수", "영희", "민수"]
점수들 = [85, 92, 78]

결과 = zip(이름들, 점수들)
print(list(결과))  # [('철수', 85), ('영희', 92), ('민수', 78)]

# 활용 예: for문에서 두 리스트를 동시에 순회
for 이름, 점수 in zip(이름들, 점수들):
    print(f"{이름}: {점수}점")
# 철수: 85점
# 영희: 92점
# 민수: 78점

# 3개 이상의 리스트도 가능
반 = ["1반", "2반", "3반"]
for 이름, 점수, 반이름 in zip(이름들, 점수들, 반):
    print(f"{반이름} {이름}: {점수}점")

# 활용 예: zip으로 딕셔너리 만들기
정보 = dict(zip(이름들, 점수들))
print(정보)  # {'철수': 85, '영희': 92, '민수': 78}
