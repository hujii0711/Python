"""
숫자, 리스트 등 다양한 자료형을 문자열로 변환합니다.
"""

print(str(123))  # '123'
print(str(3.14))  # '3.14'
print(str(True))  # 'True'
print(str([1, 2, 3]))  # '[1, 2, 3]'

# 활용 예: 숫자와 문자열을 합칠 때 (+ 연산은 같은 타입끼리만 가능)
나이 = 25
# print("나이: " + 나이)  # TypeError! 문자열 + 정수는 불가능
print("나이: " + str(나이))  # '나이: 25' (정상 작동)

# f-string을 쓰면 str() 없이도 되지만, 개념 이해는 필수
print(f"나이: {나이}")  # '나이: 25' (f-string 내부에서 자동 변환됨)
