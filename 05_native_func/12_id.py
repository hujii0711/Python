"""
파이썬에서 모든 객체(변수, 값 등)는 메모리 상에 저장되는데, `id()`는 그 객체의 고유한 식별 번호(메모리 주소 기반)를 반환합니다.
"""

a = 10
print(id(a))  # 예: 140712834567232 (실행할 때마다 다를 수 있음)

# 같은 값을 가진 두 변수가 같은 객체인지 확인할 때 유용
b = 10
print(id(a) == id(b))  # True (작은 정수는 파이썬이 재사용함)

# 리스트는 다름 (가변 객체라서 각각 새로 생성됨)
list1 = [1, 2, 3]
list2 = [1, 2, 3]
print(id(list1) == id(list2))  # False (값은 같지만 서로 다른 객체)
print(list1 == list2)  # True (값 비교는 이걸로)
